"""Build docs/compute_plan.md from the 1-epoch timing probe (results/probe/runs.csv).

GPU hours = seconds per epoch (probe) x paper epochs x runs, plus a fixed per-run overhead and
a relative overhead for dev evaluation and checkpointing. The budget ladder is simulated step
by step; configs/matrix.yaml must be edited to the chosen step (the script warns if it differs).
"""
import copy
import csv
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from lora.matrix import load_matrix  # noqa: E402

BUDGET_H = 72.0
EVAL_OVERHEAD = 1.05     # dev evaluation + per-epoch checkpoint write, relative to train time
RUN_OVERHEAD_S = 30.0    # model load, tokenisation, start-up per run
TASKS = ["rte", "mrpc", "stsb", "cola", "sst2"]


def probe_times() -> dict:
    out = {}
    with open(ROOT / "results" / "probe" / "runs.csv", newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            out[(r["method"], r["task"])] = float(r["train_time_s"])
    return out


def epochs(method: str, task: str) -> int:
    name = "lora_roberta_base" if method == "lora" else "ft_roberta_base"
    cfg = yaml.safe_load((ROOT / "configs" / f"{name}.yaml").read_text(encoding="utf-8"))
    return cfg["tasks"][task]["epochs"]


def run_hours(times: dict, method: str, task: str) -> float:
    sec = times[(method, task)] * epochs(method, task) * EVAL_OVERHEAD + RUN_OVERHEAD_S
    return sec / 3600.0


def core_hours(m: dict, times: dict) -> dict:
    out = {}
    for stage in m["core"]["stages"]:
        for task in stage["tasks"]:
            for method in m["core"]["methods"]:
                out[(method, task)] = run_hours(times, method, task) * len(stage["seeds"])
    return out


def rank_hours(m: dict, times: dict) -> dict:
    c = m["rank_ablation"]
    new_ranks = [r for r in c["ranks"] if r != m["core"]["lora"]["r"]]
    out = {}
    for stage in c["stages"]:
        for task in stage["tasks"]:
            out[task] = run_hours(times, "lora", task) * len(stage["seeds"]) * len(new_ranks)
    return out


def proj_hours(m: dict, times: dict) -> dict:
    c = m["projection_ablation"]
    out = {}
    for task in c["tasks"]:
        n_new = sum(1 for v in c["variants"] if v["name"] != "qv")
        out[task] = run_hours(times, "lora", task) * len(c["seeds"]) * n_new
    return out


def ladder(m: dict) -> list[tuple[str, dict]]:
    """Cumulative budget-reduction steps, starting from the full 5-seed matrix."""
    full = copy.deepcopy(m)
    for blk in (full["core"], full["rank_ablation"]):
        for st in blk["stages"]:
            st["seeds"] = [0, 1, 2, 3, 4]
    steps = [("Full matrix (5 seeds everywhere)", full)]
    s1 = copy.deepcopy(full)
    s1["rank_ablation"]["stages"] = [st for st in s1["rank_ablation"]["stages"]
                                     if st["tasks"] != ["sst2"]]
    steps.append(("1. Drop SST-2 from the rank ablation", s1))
    s2 = copy.deepcopy(s1)
    for st in s2["rank_ablation"]["stages"]:
        if "cola" in st["tasks"]:  # split CoLA into its own 3-seed stage
            st["tasks"] = [t for t in st["tasks"] if t != "cola"]
    s2["rank_ablation"]["stages"].append({"tasks": ["cola"], "seeds": [0, 1, 2]})
    steps.append(("2. Rank-ablation seeds 5 -> 3 for CoLA", s2))
    s3 = copy.deepcopy(s2)
    for st in s3["core"]["stages"]:
        if st["tasks"] == ["sst2"]:
            st["seeds"] = [0, 1, 2]
    steps.append(("3. Core seeds 5 -> 3 for SST-2", s3))
    return steps


def total(m: dict, times: dict) -> float:
    return sum(core_hours(m, times).values()) + sum(rank_hours(m, times).values())


def main() -> int:
    times = probe_times()
    m = load_matrix()
    steps = ladder(m)
    chosen = len(steps) - 1
    for i, (_, sm) in enumerate(steps):
        if total(sm, times) <= BUDGET_H:
            chosen = i
            break
    chosen_m = steps[chosen][1]

    def seeds_of(mm):
        return ([(s["tasks"], s["seeds"]) for s in mm["core"]["stages"]],
                [(s["tasks"], s["seeds"]) for s in mm["rank_ablation"]["stages"]])

    consistent = seeds_of(chosen_m) == seeds_of(m)

    L = ["# Compute plan", "",
         "Generated by `scripts/estimate_compute.py` from the one-epoch timing probe "
         "(`results/probe/runs.csv`); do not edit by hand.", "",
         "## Requirements", "",
         "- The machine must stay awake for the whole sweep: sleep and hibernation disabled "
         "(Windows: `powercfg /change standby-timeout-ac 0` and `powercfg /hibernate off`).",
         "- The GPU must be free of other workloads; the benchmarks in `src/bench.py` additionally "
         "require that no training job is running.",
         "- The queue runner resumes after interruptions: re-run the same `make` target.", "",
         "## Timing probe (1 epoch, seed 0)", "",
         "| Task | LoRA s/epoch | FT s/epoch | LoRA paper epochs | FT epochs |",
         "|---|---|---|---|---|"]
    for t in TASKS:
        L.append(f"| {t} | {times[('lora', t)]:.1f} | {times[('ft', t)]:.1f} | "
                 f"{epochs('lora', t)} | {epochs('ft', t)} |")
    L += ["", f"Estimate = s/epoch x epochs x {EVAL_OVERHEAD} (dev evaluation and checkpoint "
          f"overhead) + {RUN_OVERHEAD_S:.0f} s start-up per run.", "",
          f"## Main budget: {BUDGET_H:.0f} GPU hours (core + rank ablation)", "",
          "| Step | Core LoRA h | Core FT h | Rank ablation h | Total h | Fits |",
          "|---|---|---|---|---|---|"]
    for name, sm in steps:
        ch = core_hours(sm, times)
        lo = sum(v for (me, _), v in ch.items() if me == "lora")
        ft = sum(v for (me, _), v in ch.items() if me == "ft")
        ra = sum(rank_hours(sm, times).values())
        L.append(f"| {name} | {lo:.1f} | {ft:.1f} | {ra:.1f} | {lo + ft + ra:.1f} | "
                 f"{'yes' if lo + ft + ra <= BUDGET_H else 'no'} |")
    L += ["", f"Selected: **{steps[chosen][0]}**"
          + ("" if total(chosen_m, times) <= BUDGET_H else
             " (the estimate still exceeds the budget; runs follow the priority order and "
             "anything unfinished is listed as not run)") + ".", "",
          "### Per-task breakdown of the selected plan (GPU hours)", "",
          "| Task | Core LoRA | Core FT | Rank ablation (new ranks) |", "|---|---|---|---|"]
    ch, rh = core_hours(chosen_m, times), rank_hours(chosen_m, times)
    for t in TASKS:
        L.append(f"| {t} | {ch.get(('lora', t), 0):.1f} | {ch.get(('ft', t), 0):.1f} | "
                 f"{rh.get(t, 0):.1f} |")
    ph = proj_hours(m, times)
    L += ["", "## Projection ablation (separate, not part of the main budget)", "",
          "Wq only (r=16), Wv only (r=16) and Wq+Wk+Wv+Wo (r=4); the Wq+Wv runs are reused "
          "from the core.", "", "| Task | GPU hours |", "|---|---|"]
    for t, h in ph.items():
        L.append(f"| {t} | {h:.1f} |")
    L.append(f"| **total** | **{sum(ph.values()):.1f}** |")
    L += ["", f"Current `configs/matrix.yaml` matches the selected step: "
          f"{'yes' if consistent else 'NO - edit the matrix and record it in docs/deviations.md'}."]
    out = ROOT / "docs" / "compute_plan.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"selected step {chosen}: {steps[chosen][0]}; total {total(chosen_m, times):.1f} h; "
          f"matrix consistent: {consistent}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
